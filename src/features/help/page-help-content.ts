/**
 * 八个页面的内置操作手册数据。
 *
 * 这里只保存面向用户的静态说明，不能复制 Rust 的状态机或校验逻辑。文字中的
 * 默认值、动作语义和验收边界应与 docs/requirements.md 保持同步。
 */

export type PageHelpSection = {
  /** Accordion 的稳定键，同时便于测试精确定位章节。 */
  id: string;
  title: string;
  description?: string;
  steps: readonly string[];
  notes?: readonly string[];
};

export type PageHelpGuide = {
  title: string;
  summary: string;
  recommendedFor: string;
  sections: readonly PageHelpSection[];
};

function generalGuide(
  title: string,
  summary: string,
  sections: readonly [string, string, string, string, string],
): PageHelpGuide {
  return {
    title,
    summary,
    recommendedFor: `需要在${title}页面完成配置、核对 Rust 返回结果并保留明确操作边界时使用。`,
    sections: sections.map((section, index) => ({
      id: `${title}-${index}`,
      title: section,
      steps: [
        `先读取页面显示的当前状态，再开始${section}。`,
        "所有列表、校验和持久化结果均以 Rust 命令返回值为准。",
        "输入只在当前表单中收集，不在浏览器侧实现代理业务规则。",
        "出现错误时保留 Rust 返回的字段和消息，修正后重新执行操作。",
      ],
    })),
  };
}

